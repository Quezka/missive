"""What the application needs from the outside world, as interfaces."""
from __future__ import annotations

from datetime import datetime
from typing import Protocol

from ..domain import Account, Folder, Message


class MailSource(Protocol):
    """A mailbox on a server. Read-only: nothing here changes, moves or deletes mail."""

    def folders(self, account: Account) -> list[Folder]: ...

    def headers(self, account: Account, folder: str, after_uid: int) -> list[Message]:
        """Messages in `folder` with a UID above `after_uid`, without their bodies."""
        ...

    def body(self, account: Account, folder: str, uid: int) -> tuple[str | None, str | None]:
        """(plain text, HTML) of one message."""
        ...

    def check(self, account: Account, secret: str) -> None:
        """Sign in with this secret (the password, or the OAuth refresh token for a Google or Microsoft
        account) and look at the folder list; raises SourceError when it fails.
        Network only (no store access), so it may run on a worker thread."""
        ...


class OAuthClient(Protocol):
    """Signing in to Google or Microsoft without a password: the user approves in their browser."""

    def available(self, provider: str) -> bool:
        """Whether this provider's client ID has been set up."""
        ...

    def authorize(self, provider: str, address: str) -> str:
        """Open the browser, wait for the user to approve, and return the refresh token (a secret that
        goes to the keyring). Blocks for up to a few minutes, so run it on a worker thread."""
        ...

    def cancel(self) -> None:
        """Stop an `authorize` that is waiting for the browser (it then raises SourceError)."""
        ...

    def access_token(self, provider: str, refresh_token: str) -> str:
        """A short-lived access token for IMAP, from the refresh token."""
        ...


class PasswordStore(Protocol):
    """Where passwords live: the operating system's keyring, never the database."""

    def get(self, account_id: int) -> str: ...
    def set(self, account_id: int, password: str) -> None: ...
    def delete(self, account_id: int) -> None: ...


class MessageStore(Protocol):
    def accounts(self) -> list[Account]: ...
    def add_account(self, account: Account) -> Account: ...
    def remove_account(self, account_id: int) -> None: ...
    def save_folders(self, folders: list[Folder]) -> None: ...
    def folders(self, account_id: int | None = None) -> list[Folder]: ...
    def max_uid(self, account_id: int, folder: str) -> int: ...
    def save_messages(self, messages: list[Message]) -> int:
        """Store messages not seen before; returns how many were new."""
        ...

    def messages(self, account_id: int | None, folder: str | None, limit: int) -> list[Message]: ...
    def message(self, account_id: int, folder: str, uid: int) -> Message | None: ...
    def save_body(self, account_id: int, folder: str, uid: int, text: str | None, html: str | None) -> None: ...
    def set_seen(self, account_id: int, folder: str, uid: int, seen: bool) -> None: ...
    def set_flagged(self, account_id: int, folder: str, uid: int, flagged: bool) -> None: ...
    def search(self, query: str, limit: int) -> list[Message]: ...
    def unread_counts(self) -> dict[tuple[int, str], int]: ...
    def totals(self) -> dict[tuple[int, str], int]: ...


class Clock(Protocol):
    def now(self) -> datetime: ...
